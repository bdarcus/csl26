#!/usr/bin/env node
// Generate outward-facing data-model and ingest-mapping reference docs from
// already-generated machine sources (docs/schemas/bib.json, docs/schemas/type-map.json)
// and the worked examples under examples/data-model/.
//
// Run via `just schema-gen` (kept in sync with `docs/schemas/*.json`) or directly:
//   node scripts/build-data-model-reference.js
//
// Pass --out-dir <path> to write into an alternate root (same relative
// layout) instead of docs/reference/ — used by CI to diff generated output
// against the committed files without touching the working tree.
//
// Outputs (relative to the output root, docs/reference/ by default):
//   generated/DATA_MODEL_FIELDS.md
//   generated/CSL_JSON_MAPPING.md
//   BIBLATEX_MAPPING.md
//   NATIVE_FORMAT.md

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BIB_SCHEMA_PATH = path.join(ROOT, 'docs/schemas/bib.json');
const TYPE_MAP_PATH = path.join(ROOT, 'docs/schemas/type-map.json');
const EXAMPLES_DIR = path.join(ROOT, 'examples/data-model');

const GENERATED_HEADER = '<!-- GENERATED by scripts/build-data-model-reference.js — do not edit -->';

function refName(ref) {
    return ref.replace('#/$defs/', '');
}

// Resolve a single (non-union) schema entry to a short, human-readable type name.
function resolveEntry(entry, defs) {
    if (entry.$ref) return refName(entry.$ref);
    if (entry.const !== undefined) return `\`${JSON.stringify(entry.const)}\``;
    if (Array.isArray(entry.enum)) return entry.enum.map((v) => `\`${v}\``).join(' \\| ');

    // schemars renders an optional scalar as e.g. `"type": ["string", "null"]`
    // rather than wrapping it in anyOf; collapse that down to the non-null type.
    let type = entry.type;
    if (Array.isArray(type)) {
        const nonNull = type.filter((t) => t !== 'null');
        type = nonNull.length === 1 ? nonNull[0] : nonNull;
    }

    if (type === 'array') {
        if (Array.isArray(entry.items)) {
            return `[${entry.items.map((i) => resolveEntry(i, defs)).join(', ')}][]`;
        }
        if (entry.items && Array.isArray(entry.items.prefixItems)) {
            return `[${entry.items.prefixItems.map((i) => resolveEntry(i, defs)).join(', ')}][]`;
        }
        if (entry.items) return `${resolveEntry(entry.items, defs)}[]`;
        return 'array';
    }
    if (type === 'object' && entry.additionalProperties) {
        return `map<string, ${resolveEntry(entry.additionalProperties, defs)}>`;
    }
    if (Array.isArray(type)) return type.length ? type.join(' \\| ') : 'null';
    if (type) return type;
    return 'unknown';
}

// Resolve a field schema (possibly anyOf/oneOf-wrapped, usually to allow null)
// to a short type string, dropping the null branch since the Required column
// already conveys optionality.
function resolveType(schema, defs) {
    const union = schema.anyOf || schema.oneOf;
    if (union) {
        const nonNull = union.filter((e) => e.type !== 'null');
        const parts = [...new Set(nonNull.map((e) => resolveEntry(e, defs)))];
        return parts.join(' \\| ') || 'null';
    }
    return resolveEntry(schema, defs);
}

// Resolve a field's description: the field's own doc comment (via schemars)
// if present, else the referenced type's own top-level description as a
// fallback, first paragraph only, whitespace collapsed to fit a table cell.
function resolveDescription(schema, defs) {
    if (schema.description) return collapse(schema.description);

    let ref = null;
    if (schema.$ref) ref = schema.$ref;
    else if (schema.anyOf) ref = (schema.anyOf.find((e) => e.$ref) || {}).$ref;
    else if (schema.oneOf) ref = (schema.oneOf.find((e) => e.$ref) || {}).$ref;
    else if (schema.type === 'array' && schema.items && schema.items.$ref) ref = schema.items.$ref;

    if (ref) {
        const def = defs[refName(ref)];
        if (def && def.description) return collapse(def.description);
    }
    return '—';
}

function collapse(text) {
    const firstParagraph = text.split('\n\n')[0];
    return firstParagraph.replace(/\s+/g, ' ').trim();
}

function fieldTable(properties, required, defs) {
    const requiredSet = new Set(required || []);
    const rows = Object.entries(properties)
        .filter(([name]) => name !== 'class')
        .map(([name, schema]) => {
            const type = resolveType(schema, defs);
            const req = requiredSet.has(name) ? 'yes' : '';
            const desc = resolveDescription(schema, defs);
            return `| \`${name}\` | ${type} | ${req} | ${desc} |`;
        });
    return ['| Field | Type | Required | Description |', '|---|---|---|---|', ...rows].join('\n');
}

function isEnumDef(def) {
    if (!def || !Array.isArray(def.oneOf) || def.oneOf.length === 0) return false;
    if (def.oneOf.every((e) => 'const' in e)) return true;
    return def.oneOf.length === 1 && Array.isArray(def.oneOf[0].enum);
}

function enumValues(def) {
    if (def.oneOf.every((e) => 'const' in e)) {
        return def.oneOf.map((e) => ({ value: e.const, description: e.description || '' }));
    }
    return def.oneOf[0].enum.map((v) => ({ value: v, description: '' }));
}

function buildDataModelFields(schema) {
    const defs = schema.$defs;
    const ir = defs.InputReference;
    const lines = [GENERATED_HEADER, '', '# Citum Data Model — Field Reference', ''];
    lines.push(
        'One section per `InputReference` class (see the `class` discriminator), each with',
        'its field table. Narrative context lives in [DATA_MODEL.md](../DATA_MODEL.md);',
        'this page is the generated field-level detail it links out to.',
        ''
    );

    for (const variant of ir.oneOf) {
        const className = variant.properties.class.const;
        lines.push(`## \`${className}\``, '', variant.description, '', fieldTable(variant.properties, variant.required, defs), '');
    }

    // Closed vocabularies: every $ref reachable from InputReference's variants
    // that resolves to a def shaped as a flat string enum.
    const refNames = [...new Set([...JSON.stringify(ir.oneOf).matchAll(/#\/\$defs\/(\w+)/g)].map((m) => m[1]))].sort();
    const vocabNames = refNames.filter((name) => isEnumDef(defs[name]));

    lines.push('## Closed Vocabularies', '');
    for (const name of vocabNames) {
        const def = defs[name];
        lines.push(`### ${name}`, '');
        if (def.description) lines.push(collapse(def.description), '');
        lines.push('| Value | Description |', '|---|---|');
        for (const { value, description } of enumValues(def)) {
            lines.push(`| \`${value}\` | ${description ? collapse(description) : '—'} |`);
        }
        lines.push('');
    }

    return lines.join('\n');
}

function buildCslJsonMapping(typeMap) {
    const lines = [
        GENERATED_HEADER,
        '',
        '# CSL-JSON to Citum Type Mapping',
        '',
        'Generated from `docs/schemas/type-map.json`\'s `csl_type_map` array. See',
        '[CSL_TYPE_CONVERSION_CONTRACT.md](../../specs/CSL_TYPE_CONVERSION_CONTRACT.md) for the',
        'conversion rationale and round-trip contract this table is asserted against.',
        '',
        '| CSL 1.0.2 Type | Citum Reference Type | Notes |',
        '|---|---|---|',
    ];
    for (const row of typeMap.csl_type_map) {
        lines.push(`| \`${row.csl_type}\` | \`${row.citum_ref_type}\` | ${row.note ? collapse(row.note) : '—'} |`);
    }
    return lines.join('\n') + '\n';
}

function buildBiblatexMapping(typeMap) {
    const lines = [
        GENERATED_HEADER,
        '',
        '# BibLaTeX to Citum Reference Mapping',
        '',
        'Generated from `docs/schemas/type-map.json`\'s `biblatex_entry_types` and',
        '`biblatex_fields` arrays, which are in turn generated from the declarative',
        'mapping tables in `crates/citum-refs/src/formats/biblatex/tables.rs` — the',
        'single source of truth for BibLaTeX conversion behavior. This file is fully',
        'generated; do not hand-edit rows here, edit `tables.rs` and run',
        '`just schema-gen`.',
        '',
        '## Entry Type Mapping',
        '',
        '| BibLaTeX Entry Type | Builder | Monograph Type | Collection Type | Serial Type | Notes |',
        '|---|---|---|---|---|---|',
    ];
    for (const row of typeMap.biblatex_entry_types) {
        lines.push(
            `| \`@${row.entry_type}\` | \`${row.builder}\` | ${row.monograph_type ? `\`${row.monograph_type}\`` : '—'} | ${row.collection_type ? `\`${row.collection_type}\`` : '—'} | ${row.serial_type ? `\`${row.serial_type}\`` : '—'} | ${row.note ? collapse(row.note) : '—'} |`
        );
    }

    const mapped = typeMap.biblatex_fields.filter((f) => f.target !== null);
    const unmapped = typeMap.biblatex_fields.filter((f) => f.target === null);

    lines.push('', '## Field Mapping: Currently Read', '', '| BibLaTeX Field | Datatype | Crate Accessor | Citum Target | Notes |', '|---|---|---|---|---|');
    for (const row of mapped) {
        lines.push(
            `| \`${row.field}\` | ${row.datatype} | ${row.crate_accessor ? `\`${row.crate_accessor}\`` : '—'} | ${row.target} | ${row.note ? collapse(row.note) : '—'} |`
        );
    }

    lines.push(
        '',
        '## Not Yet Mapped',
        '',
        'Fields with a typed accessor in the `biblatex` crate (or documented prior art) but',
        'no Citum schema slot or extraction path today. This is the gap-analysis deliverable',
        'for bean csl26-11h2 — each row below is a candidate for a follow-up bean, not a bug',
        'in the mapping tables.',
        '',
        '| BibLaTeX Field | Datatype | Crate Accessor | Notes |',
        '|---|---|---|---|'
    );
    for (const row of unmapped) {
        lines.push(
            `| \`${row.field}\` | ${row.datatype} | ${row.crate_accessor ? `\`${row.crate_accessor}\`` : '—'} | ${row.note ? collapse(row.note) : '—'} |`
        );
    }

    return lines.join('\n') + '\n';
}

function titleCase(slug) {
    return slug
        .split('-')
        .map((w) => w[0].toUpperCase() + w.slice(1))
        .join(' ');
}

// Narrative order: the five structural classes, then flat classes, matching
// the class ordering DATA_MODEL.md introduces them in. Falls back to
// alphabetical for any fixture not named here.
const NATIVE_FORMAT_ORDER = [
    'monograph',
    'collection',
    'collection-component',
    'serial',
    'serial-component',
    'patent',
    'dataset',
];

function buildNativeFormat() {
    const files = fs
        .readdirSync(EXAMPLES_DIR)
        .filter((f) => f.endsWith('.yaml'))
        .sort((a, b) => {
            const ia = NATIVE_FORMAT_ORDER.indexOf(a.replace(/\.yaml$/, ''));
            const ib = NATIVE_FORMAT_ORDER.indexOf(b.replace(/\.yaml$/, ''));
            if (ia === -1 && ib === -1) return a.localeCompare(b);
            if (ia === -1) return 1;
            if (ib === -1) return -1;
            return ia - ib;
        });

    const lines = [
        GENERATED_HEADER,
        '',
        '# Citum Native Format — Worked Examples',
        '',
        'One worked example per reference class, inlined from the test-backed fixtures',
        'under `examples/data-model/`. Each fixture round-trips through',
        '`InputReference` in `crates/citum-refs`\' example-verification test, so a stale',
        'example fails CI rather than silently drifting from the schema. See',
        '[DATA_MODEL.md](DATA_MODEL.md) for the concepts these examples illustrate.',
        '',
    ];

    for (const file of files) {
        const slug = file.replace(/\.yaml$/, '');
        const content = fs.readFileSync(path.join(EXAMPLES_DIR, file), 'utf8');
        const commentLines = [];
        for (const line of content.split('\n')) {
            if (line.startsWith('#')) commentLines.push(line.replace(/^#\s?/, ''));
            else break;
        }
        lines.push(`## ${titleCase(slug)}`, '');
        if (commentLines.length) lines.push(commentLines.join(' '), '');
        lines.push('```yaml', content.trimEnd(), '```', '');
    }

    return lines.join('\n');
}

function writeIfChanged(outPath, content) {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, content);
    console.log(`Built: ${path.relative(ROOT, outPath)}`);
}

function parseOutDir(argv) {
    const flagIndex = argv.indexOf('--out-dir');
    if (flagIndex === -1) return path.join(ROOT, 'docs/reference');
    const value = argv[flagIndex + 1];
    if (!value) {
        console.error('--out-dir requires a path argument');
        process.exit(1);
    }
    return path.resolve(value);
}

function build() {
    const outDir = parseOutDir(process.argv.slice(2));
    const schema = JSON.parse(fs.readFileSync(BIB_SCHEMA_PATH, 'utf8'));
    const typeMap = JSON.parse(fs.readFileSync(TYPE_MAP_PATH, 'utf8'));

    writeIfChanged(path.join(outDir, 'generated/DATA_MODEL_FIELDS.md'), buildDataModelFields(schema));
    writeIfChanged(path.join(outDir, 'generated/CSL_JSON_MAPPING.md'), buildCslJsonMapping(typeMap));
    writeIfChanged(path.join(outDir, 'BIBLATEX_MAPPING.md'), buildBiblatexMapping(typeMap));
    writeIfChanged(path.join(outDir, 'NATIVE_FORMAT.md'), buildNativeFormat());
}

build();
